@dataclass
class ProbeSession:
    """Adaptateur SSH de test : la frontiere reseau est remplacee, pas PlugArr."""

    fingerprint: str = "SHA256:serveur-maison"

    def run(self, _command: str, *, stdin: bytes | None = None):
        return (
            0,
            (
                "system=Linux\nmachine=aarch64\nuid=1000\ngid=10\n"
                "home=/home/yannick\ndocker=29.8.1"
            ),
            "",
        )

    def close(self):
        pass


@dataclass
class DeploySession:
    """Machine SSH observable depuis le contrat public de deploiement."""

    fingerprint: str = "SHA256:serveur-maison"

    def __post_init__(self):
        self.commands: list[str] = []
        self.files: dict[str, tuple[bytes, int]] = {}

    def run(self, command: str, *, stdin: bytes | None = None):
        self.commands.append(command)
        if "stat -c %g /var/run/docker.sock" in command:
            return 0, "sock_gid=998\n", ""
        return (
            0,
            (
                '{"kind":"progress","phase":"preflight","message":"Docker pret"}\n'
                '{"kind":"done","status":"done"}'
            ),
            "",
        )

    def upload(self, path: str, data: bytes, *, mode: int = 0o600):
        self.files[path] = (data, mode)

    def close(self):
        pass


def test_probe_decrit_le_serveur_sans_exposer_le_secret():
    target = RemoteTarget(host="192.168.1.50", port=22, username="yannick")
    credentials = RemoteCredentials(password="mot-de-passe-tres-secret")

    result = probe(target, credentials, connect=lambda *_: ProbeSession())

    assert result.fingerprint == "SHA256:serveur-maison"
    assert result.system == "Linux"
    assert result.machine == "aarch64"
    assert (result.uid, result.gid) == (1000, 10)
    assert result.home == "/home/yannick"
    assert result.docker_version == "29.8.1"
    assert result.ready
    assert "mot-de-passe-tres-secret" not in repr(result)


