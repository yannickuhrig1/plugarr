def test_entree_distante_accepte_ancien_catalogue_sans_conteneurs_techniques(
    monkeypatch, capsys
):
    """Le lanceur envoye par l'EXE corrige l'image admin deja publiee."""
    cfg = SimpleNamespace(remote_access=SimpleNamespace(mode="local"), services={})

    def old_get(service_id):
        if service_id == "sonarr":
            return SimpleNamespace(display_name="Sonarr")
        raise KeyError(f"service inconnu: {service_id}")

    catalog = SimpleNamespace(get=old_get)
    checked = []

    def old_install(_cfg, _project_dir, *, on_progress, on_step):
        for service_id in ("sonarr", "docker-proxy", "veille", "console"):
            checked.append(catalog.get(service_id).display_name)

    old_orchestrator = SimpleNamespace(
        catalog=catalog,
        preflight=lambda _cfg, _dir: [],
        install=old_install,
    )
    fake_package = SimpleNamespace(
        migrations=SimpleNamespace(lire=lambda _path: (cfg, [])),
        orchestrator=old_orchestrator,
        remote_access=SimpleNamespace(),
    )
    monkeypatch.setitem(sys.modules, "plugarr", fake_package)
    monkeypatch.setattr(sys, "argv", ["remote-entry", "/srv/plugarr", "install"])

    with pytest.raises(SystemExit) as result:
        exec(REMOTE_ENTRYPOINT, {"__name__": "__main__"})  # noqa: S102

    assert result.value.code == 0
    assert checked == ["Sonarr", "docker-proxy", "veille", "console"]
    assert catalog.get is old_get
    assert json.loads(capsys.readouterr().out.splitlines()[-1]) == {
        "kind": "done",
        "status": "done",
    }


def test_entree_reset_ne_touche_qu_a_l_etat_de_l_ancienne_pile(tmp_path, monkeypatch, capsys):
    old_bytes = b"ancienne pile"
    old_sha = hashlib.sha256(old_bytes).hexdigest()
    backup = tmp_path / f".stack-before-remote-{old_sha[:16]}.yml"
    backup.write_bytes(old_bytes)
    root = str(tmp_path / "config")
    data = str(tmp_path / "data")
    previous = SimpleNamespace(
        project_name="plugarr", config_root=root, data_root=data, services={"qui": object()}
    )
    current = SimpleNamespace(
        project_name="plugarr", config_root=root, data_root=data,
        services={}, remote_access=SimpleNamespace(mode="local"),
    )
    removed = []
    old_catalog = SimpleNamespace(STARTUP_ORDER=("qui",), get=lambda _sid: SimpleNamespace(display_name="qui"))
    old_orchestrator = SimpleNamespace(
        catalog=old_catalog, preflight=lambda *_: [], existing_configs=lambda _cfg: ["qui"],
        reset_installation_configs=lambda cfg, path, ids: removed.append(
            (cfg, path, ids)
        ) or [path / "config"],
        install=lambda *_args, **_kwargs: [], _compose_service_name=lambda sid: sid,
    )
    fake_package = SimpleNamespace(
        migrations=SimpleNamespace(lire=lambda path: (current if path.name == "stack.yml" else previous, [])),
        orchestrator=old_orchestrator, remote_access=SimpleNamespace(), catalog=old_catalog,
    )
    monkeypatch.setitem(sys.modules, "plugarr", fake_package)
    monkeypatch.setattr(
        sys, "argv",
        ["remote-entry", str(tmp_path), "reset-install", old_sha, "plugarr:admin"],
    )

    with pytest.raises(SystemExit) as result:
        exec(REMOTE_ENTRYPOINT, {"__name__": "__main__"})  # noqa: S102

    assert result.value.code == 0
    assert removed == [(previous, tmp_path, ["qui"])]
    assert json.loads(capsys.readouterr().out.splitlines()[-1]) == {"kind": "done", "status": "done"}


