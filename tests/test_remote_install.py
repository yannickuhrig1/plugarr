def test_connecteur_charge_la_cle_privee_depuis_la_memoire(monkeypatch):
    calls: dict[str, object] = {}

    class FakeKey:
        fingerprint = "SHA256:cle-distante"

    class FakeRSAKey:
        @classmethod
        def from_private_key(cls, stream, password=None):
            calls["key_text"] = stream.read()
            calls["passphrase"] = password
            return FakeKey()

    class FakeClient:
        def set_missing_host_key_policy(self, policy):
            calls["policy"] = type(policy).__name__

        def connect(self, **kwargs):
            calls["connect"] = kwargs

        def get_transport(self):
            return SimpleNamespace(get_remote_server_key=lambda: FakeKey())

        def close(self):
            calls["closed"] = True

    fake_paramiko = SimpleNamespace(
        SSHClient=FakeClient,
        AutoAddPolicy=type("AutoAddPolicy", (), {}),
        RSAKey=FakeRSAKey,
        ECDSAKey=type("ECDSAKey", (), {}),
        Ed25519Key=type("Ed25519Key", (), {}),
        SSHException=RuntimeError,
    )
    monkeypatch.setitem(__import__("sys").modules, "paramiko", fake_paramiko)

    session = connect_paramiko(
        RemoteTarget(host="nas.local", port=2222, username="yannick"),
        RemoteCredentials(
            private_key="-----BEGIN PRIVATE KEY-----\nsecret-key\n-----END PRIVATE KEY-----",
            passphrase="phrase-secrete",
        ),
    )

    assert session.fingerprint == "SHA256:cle-distante"
    assert calls["key_text"] == (
        "-----BEGIN PRIVATE KEY-----\nsecret-key\n-----END PRIVATE KEY-----"
    )
    assert calls["passphrase"] == "phrase-secrete"
    assert calls["connect"]["hostname"] == "nas.local"
    assert calls["connect"]["port"] == 2222
    assert calls["connect"]["allow_agent"] is False
    assert calls["connect"]["look_for_keys"] is False


def test_deploy_utilise_sudo_sans_mettre_son_mot_de_passe_dans_la_commande():
    class SudoSession(DeploySession):
        def __post_init__(self):
            super().__post_init__()
            self.stdin_values: list[bytes | None] = []
            self.prepares = 0

        def run(self, command: str, *, stdin: bytes | None = None):
            self.commands.append(command)
            self.stdin_values.append(stdin)
            if "stat -c %g /var/run/docker.sock" in command:
                self.prepares += 1
                if self.prepares == 1:
                    return 1, "", "Permission denied"
                return 0, "sock_gid=998\n", ""
            return 0, '{"kind":"done","status":"done"}', ""

    session = SudoSession()
    deploy(
        RemoteTarget(
            host="nas.local",
            username="yannick",
            expected_fingerprint=session.fingerprint,
        ),
        RemoteCredentials(password="ssh-secret", sudo_password="sudo-secret"),
        RemoteDeployment(
            project_dir="/volume1/docker/plugarr",
            config_root="/volume1/docker/plugarr/config",
            data_root="/volume1/data",
            uid=1000,
            gid=10,
            stack_yaml="version: 1\nservices: {}\n",
            image="ghcr.io/example/plugarr:test",
        ),
        connect=lambda *_: session,
    )

    assert session.stdin_values[1] == b"sudo-secret\n"
    assert "sudo -S" in session.commands[1]
    assert "sudo-secret" not in repr(session.commands)
    docker_command = session.commands[-1]
    assert "--user 1000:10" not in docker_command


